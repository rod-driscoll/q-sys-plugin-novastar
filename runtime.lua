	local function assertBytesEqual(name, original, built)
		-- original: raw cmd bytes (no 55 AA preamble, no checksum)
		-- built: full packet including preamble(2) + checksum(2)
		-- so built[3..n-2] should match original[1..#original]
		local ok = (#original + 4 == #built)
		if ok then
			for i = 1, #original do
				if original[i] ~= built[i + 2] then ok = false; break end
			end
		end
		if not ok then
			print("MISMATCH: " .. name)
			print("  original cmd: " .. hexDump(original))
			print("  built pkt:    " .. hexDump(built))
		else
			print("OK: " .. name)
		end
	end

